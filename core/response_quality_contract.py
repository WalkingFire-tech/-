# ============================================================
# 六、辅助函数
# ============================================================
def is_perfunctory(response: str, length_threshold: int = 120) -> bool:
    """检查回复是否包含敷衍关键词且长度不足"""
    return any(kw in response for kw in PERFUNCTORY_KEYWORDS) and len(response) < length_threshold


def has_contradiction(response: str) -> bool:
    """检查回复是否含矛盾词对（简单词级检测）"""
    for w1, w2 in CONTRADICTION_PAIRS:
        if w1 in response and w2 in response:
            return True
    return False


def has_explanatory_content(response: str) -> bool:
    """检查回复是否含解释性关键词"""
    return any(kw in response for kw in EXPLANATORY_KEYWORDS)


def has_give_up(response: str) -> bool:
    """检查回复是否含放弃性语言"""
    return any(phrase in response for phrase in GIVE_UP_PHRASES)
