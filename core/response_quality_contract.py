from typing import List, Tuple, Final

# ============================================================
# 一、敷衍关键词（出现 + 短回复时判定为敷衍）
# ============================================================
PERFUNCTORY_KEYWORDS: Final[List[str]] = [
    "我不知道", "无法回答", "请稍后", "请稍后重试", "系统错误",
    "无法访问", "无法直接", "没有能力", "不能访问", "无法获取数据",
    "我无法访问", "我无法直接", "我不能访问", "我没有能力",
    "我无法连接", "我无法执行", "我无法获取", "我无法读取",
    "无法直接访问", "无法直接操作", "无法直接执行",
    "作为ai", "作为一个ai", "作为语言模型",
    "我建议你", "你可以自己", "你需要手动",
]

# ============================================================
# 二、矛盾词对（同一回复中同时出现则触发逻辑自洽怀疑）
# ============================================================
# 注意：只有两侧出现在"同一主语范围"内才算真矛盾，
# 但当前实现仅做词级检测，全文本范围内任何位置命中即报警。
# 后续可升级为句法级检测。
CONTRADICTION_PAIRS: Final[List[Tuple[str, str]]] = [
    ("不可能", "可以"), ("错误", "正确"),
    ("必须", "可以不"), ("永远", "有时"), ("所有", "某些"),
    ("一定", "可能不"), ("必然", "偶然"), ("总是", "从不"),
]
# 豁免条件：如果"无法"+"可以"分属不同段落/句子且主语不同，不应视为矛盾
# 但当前版本暂不移除"无法"+"可以"，因为它的误报率最高

# ============================================================
# 三、解释性关键词（长回复缺少这些词时可能被判定为缺乏解释）
# ============================================================
EXPLANATORY_KEYWORDS: Final[List[str]] = [
    "因为", "由于", "原因是", "所以", "因此",
    "意味着", "说明", "表明",
    "通过", "利用", "基于", "根据",
]

# ============================================================
# 四、放弃性语言（出现即判定为"永不放弃"违规）
# ============================================================
GIVE_UP_PHRASES: Final[List[str]] = [
    "我放弃了", "无法继续", "不再尝试", "彻底失败",
]

